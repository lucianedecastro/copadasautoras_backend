package br.com.copadasautoras.entity;

public enum CategoriaLance {

    /**
     * Imprensa: matérias, entrevistas em rádio/TV,
     * participações e menções na mídia.
     */
    CLIPPING,

    /**
     * Anúncios de apoio institucional, patrocínio
     * ou novas parcerias.
     */
    APOIO_PATROCINIO,

    /**
     * Anúncios ligados às embaixadoras da Copa.
     */
    EMBAIXADORA,

    /**
     * Conteúdos próprios da Copa que não são clipping
     * nem anúncio (temas, bastidores, marcos).
     */
    TEMA
}
